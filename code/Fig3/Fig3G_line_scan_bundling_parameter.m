%% ============================================================
% SAME-LOCATION AVERAGED LINE-SCAN COMPARISON
% FRAME 2 VS FRAME 10 (OR ANY TWO FRAMES)
%
% This version calculates the bundling parameter from the
% OVERALL AVERAGED horizontal line scan inside the ROI.
%
% Procedure:
%   1. Select one rectangular ROI on the early frame.
%   2. Apply the same ROI to the late frame.
%   3. Average all horizontal line scans in the ROI:
%
%          I_avg(x) = mean_y[I(x,y)]
%
%   4. Calculate one bundling parameter from that averaged profile:
%
%                    std_x(I_avg)
%          BP_avg = --------------
%                   mean_x(I_avg)
%
% This is different from the previous row-by-row definition:
%
%          mean_y[std_x(I_row)/mean_x(I_row)]
%
% The present script uses ONLY the averaged-profile definition.
%% ============================================================

clearvars;
close all;
clc;

%% ============================================================
% 1. USER SETTINGS
%% ============================================================

stackPath = 'PATH_TO_DATA/Experiments/TwoLightSpots_Data&PIV/set11/actin.tif';

frameEarly = 1;
frameLate  = 18;

pixelSize_um = 0.160772;

% Optional activation-circle display
showActivationCircles = true;

activationCenters_um = [ ...
    97.26706, 92.44390; ...
    97.26706, 172.82990];

activationRadii_um = [ ...
    20.0965; ...
    20.0965];

% The final profile plot uses one solid mean line with a shaded
% mean +/- SD region. No additional smoothed curve is plotted.

% false = raw fluorescence intensity
% true  = divide each profile by its own mean before plotting
normalizeProfilesForDisplay = false;

displayPercentiles = [1,99];

FZ = 21;

rgbEarly = [174,139,191]/255;
rgbLate  = [105,55,130]/255;
rgbRectangle = [255,215,70]/255;
rgbCircle = [1,1,1];

outputDir = fullfile( ...
    pwd, ...
    'AverageLineScan_BP_Comparison');

if ~isfolder(outputDir)
    mkdir(outputDir);
end

outputBaseName = sprintf( ...
    'AverageLineScan_BP_Frame%d_vs_Frame%d', ...
    frameEarly, ...
    frameLate);

saveFigures = true;
saveData = true;

%% ============================================================
% 2. LOAD FRAMES
%% ============================================================

if ~isfile(stackPath)
    error('TIFF file not found:\n%s',stackPath);
end

imageInfo = imfinfo(stackPath);
numberFrames = numel(imageInfo);

if frameEarly < 1 || ...
        frameLate > numberFrames || ...
        frameEarly >= frameLate

    error('Invalid frame selection.');
end

imageEarly = double(imread( ...
    stackPath, ...
    frameEarly, ...
    'Info', ...
    imageInfo));

imageLate = double(imread( ...
    stackPath, ...
    frameLate, ...
    'Info', ...
    imageInfo));

if ndims(imageEarly) == 3
    imageEarly = mean(imageEarly,3);
end

if ndims(imageLate) == 3
    imageLate = mean(imageLate,3);
end

if ~isequal(size(imageEarly),size(imageLate))
    error('The selected frames have different dimensions.');
end

[numberRows,numberColumns] = size(imageEarly);

%% ============================================================
% 3. ACTIVATION CIRCLES
%% ============================================================

if showActivationCircles

    activationCenters_px = ...
        activationCenters_um/pixelSize_um;

    activationRadii_px = ...
        activationRadii_um/pixelSize_um;

else

    activationCenters_px = [];
    activationRadii_px = [];

end

%% ============================================================
% 4. SELECT ROI ON EARLY FRAME
%% ============================================================

figSelect = figure( ...
    'Name','Select Same ROI', ...
    'Color','w', ...
    'Position',[100,100,950,760]);

axSelect = axes(figSelect);

displayPurpleImage( ...
    axSelect, ...
    imageEarly, ...
    displayPercentiles);

hold(axSelect,'on');

if showActivationCircles

    drawActivationCircles( ...
        axSelect, ...
        activationCenters_px, ...
        activationRadii_px, ...
        rgbCircle, ...
        2.5);

end

title( ...
    axSelect, ...
    { ...
        sprintf('Frame %d',frameEarly), ...
        'Draw the bundling ROI and double-click inside it' ...
    }, ...
    'FontWeight','normal');

roiObject = drawrectangle( ...
    axSelect, ...
    'Color',rgbRectangle, ...
    'LineWidth',3, ...
    'FaceAlpha',0.05);

wait(roiObject);

roiPosition = double(roiObject.Position);

hold(axSelect,'off');

[xStart,yStart,xEnd,yEnd] = rectangleToPixelBounds( ...
    roiPosition, ...
    numberColumns, ...
    numberRows);

roiEarly = imageEarly(yStart:yEnd,xStart:xEnd);
roiLate  = imageLate(yStart:yEnd,xStart:xEnd);

numberHorizontalLines = size(roiEarly,1);
numberPointsPerLine   = size(roiEarly,2);

%% ============================================================
% 5. AVERAGE ALL HORIZONTAL LINE SCANS
%% ============================================================

% Each row is one horizontal x-direction line scan.
% Averaging across rows gives one overall ROI profile.

averageProfileEarly = mean( ...
    roiEarly, ...
    1, ...
    'omitnan');

averageProfileLate = mean( ...
    roiLate, ...
    1, ...
    'omitnan');

%% ============================================================
% 6. CALCULATE BP FROM THE AVERAGED PROFILE
%% ============================================================

meanEarly = mean( ...
    averageProfileEarly, ...
    'omitnan');

stdEarly = std( ...
    averageProfileEarly, ...
    0, ...
    'omitnan');

meanLate = mean( ...
    averageProfileLate, ...
    'omitnan');

stdLate = std( ...
    averageProfileLate, ...
    0, ...
    'omitnan');

if meanEarly <= 0
    bpEarly = NaN;
else
    bpEarly = stdEarly/meanEarly;
end

if meanLate <= 0
    bpLate = NaN;
else
    bpLate = stdLate/meanLate;
end

bpChange = bpLate-bpEarly;

if bpEarly ~= 0 && isfinite(bpEarly)
    bpPercentChange = 100*bpChange/bpEarly;
else
    bpPercentChange = NaN;
end

%% ============================================================
% 7. PREPARE PROFILES FOR DISPLAY
%% ============================================================

if normalizeProfilesForDisplay

    plotProfileEarly = averageProfileEarly/meanEarly;
    plotProfileLate  = averageProfileLate/meanLate;

    yLabelText = 'Normalized actin intensity, I/\langleI\rangle';

else

    plotProfileEarly = averageProfileEarly;
    plotProfileLate  = averageProfileLate;

    yLabelText = 'Actin fluorescence intensity';

end

xPixels = 0:(numberPointsPerLine-1);

if isempty(pixelSize_um)

    distanceAxis = xPixels;
    xLabelText = 'Distance along x (pixels)';

else

    distanceAxis = xPixels*pixelSize_um;
    xLabelText = 'Distance along x (\mum)';

end

%% ============================================================
% 8. PRINT RESULTS
%% ============================================================

fprintf('\n============================================\n');
fprintf('AVERAGED LINE-SCAN BUNDLING PARAMETER\n');
fprintf('============================================\n');

fprintf( ...
    'Number of horizontal scans averaged: %d\n', ...
    numberHorizontalLines);

fprintf( ...
    'Frame %d: mean = %.6g, std = %.6g, BP = %.6f\n', ...
    frameEarly, ...
    meanEarly, ...
    stdEarly, ...
    bpEarly);

fprintf( ...
    'Frame %d: mean = %.6g, std = %.6g, BP = %.6f\n', ...
    frameLate, ...
    meanLate, ...
    stdLate, ...
    bpLate);

fprintf( ...
    'BP change = %.6f\n', ...
    bpChange);

fprintf( ...
    'BP percent change = %.2f %%\n', ...
    bpPercentChange);

%% ============================================================
% 9. CREATE FIGURE
%% ============================================================

figResult = figure( ...
    'Name','Averaged Line-Scan BP Comparison', ...
    'Color','w', ...
    'Position',[70,90,1550,780]);

tiledlayout( ...
    figResult, ...
    2, ...
    2, ...
    'TileSpacing','compact', ...
    'Padding','compact');

%% ---------------- Early frame ----------------

axEarly = nexttile;

displayPurpleImage( ...
    axEarly, ...
    imageEarly, ...
    displayPercentiles);

hold(axEarly,'on');

if showActivationCircles

    drawActivationCircles( ...
        axEarly, ...
        activationCenters_px, ...
        activationRadii_px, ...
        rgbCircle, ...
        2.2);

end

rectangle( ...
    axEarly, ...
    'Position',roiPosition, ...
    'EdgeColor',rgbRectangle, ...
    'LineWidth',3);

hold(axEarly,'off');

title( ...
    axEarly, ...
    sprintf('Frame %d, BP_{avg} = %.4f',frameEarly,bpEarly), ...
    'FontWeight','normal');

xlabel(axEarly,'x (pixels)');
ylabel(axEarly,'y (pixels)');

formatAxes(axEarly,FZ);

%% ---------------- Late frame ----------------

axLate = nexttile;

displayPurpleImage( ...
    axLate, ...
    imageLate, ...
    displayPercentiles);

hold(axLate,'on');

if showActivationCircles

    drawActivationCircles( ...
        axLate, ...
        activationCenters_px, ...
        activationRadii_px, ...
        rgbCircle, ...
        2.2);

end

rectangle( ...
    axLate, ...
    'Position',roiPosition, ...
    'EdgeColor',rgbRectangle, ...
    'LineWidth',3);

hold(axLate,'off');

title( ...
    axLate, ...
    sprintf('Frame %d, BP_{avg} = %.4f',frameLate,bpLate), ...
    'FontWeight','normal');

xlabel(axLate,'x (pixels)');
ylabel(axLate,'y (pixels)');

formatAxes(axLate,FZ);

%% ---------------- Averaged profile comparison ----------------
%
% Solid line:
%   mean horizontal line scan across all ROI rows.
%
% Shaded region:
%   mean +/- one standard deviation across the individual
%   horizontal line scans at each x position.

axProfile = nexttile([1,2]);

hold(axProfile,'on');

% Standard deviation across horizontal line scans at every x.
stdProfileEarly = std( ...
    roiEarly, ...
    0, ...
    1, ...
    'omitnan');

stdProfileLate = std( ...
    roiLate, ...
    0, ...
    1, ...
    'omitnan');

if normalizeProfilesForDisplay

    plotStdEarly = stdProfileEarly/meanEarly;
    plotStdLate  = stdProfileLate/meanLate;

else

    plotStdEarly = stdProfileEarly;
    plotStdLate  = stdProfileLate;

end

% Mean +/- SD envelopes.
upperEarly = plotProfileEarly + plotStdEarly;
lowerEarly = plotProfileEarly - plotStdEarly;

upperLate = plotProfileLate + plotStdLate;
lowerLate = plotProfileLate - plotStdLate;

% Shaded SD for early frame.
fill( ...
    axProfile, ...
    [distanceAxis,fliplr(distanceAxis)], ...
    [upperEarly,fliplr(lowerEarly)], ...
    rgbEarly, ...
    'FaceAlpha',0.22, ...
    'EdgeColor','none', ...
    'HandleVisibility','off');

% Shaded SD for late frame.
fill( ...
    axProfile, ...
    [distanceAxis,fliplr(distanceAxis)], ...
    [upperLate,fliplr(lowerLate)], ...
    rgbLate, ...
    'FaceAlpha',0.22, ...
    'EdgeColor','none', ...
    'HandleVisibility','off');

% One solid mean line for each frame.
plot( ...
    axProfile, ...
    distanceAxis, ...
    plotProfileEarly, ...
    '-', ...
    'Color',rgbEarly, ...
    'LineWidth',3, ...
    'DisplayName',sprintf('Frame %d: mean \\pm SD',frameEarly));

plot( ...
    axProfile, ...
    distanceAxis, ...
    plotProfileLate, ...
    '-', ...
    'Color',rgbLate, ...
    'LineWidth',3, ...
    'DisplayName',sprintf('Frame %d: mean \\pm SD',frameLate));

xlabel(axProfile,xLabelText);
ylabel(axProfile,yLabelText);

title( ...
    axProfile, ...
    { ...
        'Same-location averaged horizontal actin line-scan comparison', ...
        sprintf('Mean \\pm SD across %d horizontal scans',numberHorizontalLines) ...
    }, ...
    'FontWeight','normal');

statisticsText = sprintf( ...
    ['Frame %d: BP_{avg} = %.4f\n', ...
     'Frame %d: BP_{avg} = %.4f\n', ...
     '\\DeltaBP_{avg} = %.4f'], ...
    frameEarly, ...
    bpEarly, ...
    frameLate, ...
    bpLate, ...
    bpChange);

text( ...
    axProfile, ...
    0.98, ...
    0.95, ...
    statisticsText, ...
    'Units','normalized', ...
    'HorizontalAlignment','right', ...
    'VerticalAlignment','top', ...
    'FontSize',FZ-3, ...
    'BackgroundColor','w', ...
    'Margin',5);

legend( ...
    axProfile, ...
    'Location','best', ...
    'Box','off', ...
    'FontSize',FZ-4);

hold(axProfile,'off');

grid(axProfile,'off');
formatAxes(axProfile,FZ);

%% ============================================================
% PLOTTING: THREE SEPARATE FIGURES
%% ============================================================

%% ---------------- Common image display limits ----------------
%
% Using the same color limits for both frames makes their
% intensities directly comparable.

allImagePixels = [ ...
    imageEarly(isfinite(imageEarly)); ...
    imageLate(isfinite(imageLate))];

commonCLim = prctile( ...
    allImagePixels, ...
    displayPercentiles);

%% ============================================================
% FIGURE 1: EARLY FRAME
%% ============================================================

figEarly = figure( ...
    'Name',sprintf('Frame %d',frameEarly), ...
