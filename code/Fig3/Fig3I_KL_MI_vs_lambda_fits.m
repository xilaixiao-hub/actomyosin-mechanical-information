%% ========================================================================
% KL_STD / KL_STRAIN / SPATIAL MI VS BUNDLING PARAMETER
%
% COMBINED INDIVIDUAL-EXPERIMENT FITS
%
% Each retained experiment is fitted separately:
%
%       Response = Intercept + Slope * BundlingParameter
%
% For each analysis:
%   - filtered observations from nonrepresentative experiments are gray
%   - their individual fitted lines are gray
%   - one independently selected representative experiment is highlighted
%
% There is no pooled regression and no BP fit range.
%% ========================================================================

clearvars;
close all;
clc;

%% ========================================================================
% 1. FILES
%% ========================================================================

DATAOFKL_FILE = fullfile( ...
    'PATH_TO_DATA/Data Analysis', ...
    '2I,J,Hinsert --TwoLightSpots_KL', ...
    'DATAOFKL.mat');

BP_FILE = fullfile( ...
    'PATH_TO_DATA', ...
    'MultiExperiment_BundlingParameter_AllFrames', ...
    'BP_FirstAverage.mat');

CUMULATIVE_MI_FILE = fullfile( ...
    'PATH_TO_DATA', ...
    'TwoSpot_SpatialMI_CumulativeSTD', ...
    'spatialMI_CumulativeSTD.mat');

OUTPUT_DIR = fullfile( ...
    'PATH_TO_DATA', ...
    'KL_Strain_MI_CombinedIndividualFits');

if ~isfolder(OUTPUT_DIR)
    mkdir(OUTPUT_DIR);
end

%% ========================================================================
% 2. USER SETTINGS
%% ========================================================================

NUM_FRAMES = 18;

%% ------------------------------------------------------------------------
% Remove entire experiments
%
% Use actual experiment numbers.
%
% You may remove different experiments from each analysis.
% Use [] to retain every experiment.
%% ------------------------------------------------------------------------

experimentsToRemove_KLstd = [9];
experimentsToRemove_KLstrain = [9];
experimentsToRemove_MI = [9];

% Examples:
%
% experimentsToRemove_KLstd = [8 11];
% experimentsToRemove_KLstrain = 8;
% experimentsToRemove_MI = [10 11];

%% ------------------------------------------------------------------------
% Representative experiment for each analysis
%
% Each representative must remain after the corresponding removal list.
%% ------------------------------------------------------------------------

representativeExperiment_KLstd = 10;
representativeExperiment_KLstrain = 10;
representativeExperiment_MI = 10;

%% ------------------------------------------------------------------------
% MI variable
%
% 'raw':
%   Uses MI_Raw_nats or MI_Raw_bits.
%
% 'corrected':
%   Uses MI_BiasCorrected_nats, MI_BiasCorrected_bits, or spatialMI.
%
% 'excess':
%   Uses MI_Excess_nats or MI_Excess_bits.
%% ------------------------------------------------------------------------

MIValueMode = 'raw';

%% ------------------------------------------------------------------------
% MI frame alignment
%
% MIFrameOffset = 0:
%   BP column 1 is paired with MI column 1.
%
% MIFrameOffset = 29:
%   BP column 1 is paired with MI column 30.
%% ------------------------------------------------------------------------

MIFrameOffset = 0;

%% ------------------------------------------------------------------------
% Automatic temporal filtering
%
% Filtering uses only the response time series.
% BP and regression results are not used to identify points.
%% ------------------------------------------------------------------------

applyAutomaticFiltering = true;

autoFilter.windowSize = 7;
autoFilter.thresholdFactor = 3.0;
autoFilter.minimumWindowPoints = 4;
autoFilter.maximumConsecutiveOutliers = 3;
autoFilter.maximumExcludedFraction = 0.25;
autoFilter.minimumScaleFraction = 1e-4;
autoFilter.protectEndpoints = false;

%% ------------------------------------------------------------------------
% Plot settings
%% ------------------------------------------------------------------------

FZ = 23;
figurePosition = [100,100,850,720];

rgbPurple = [135,85,155]/255;
rgbRed = [150,26,73]/255;

rgbGrayPoint = [0.72,0.72,0.72];
rgbGrayLine = [0.48,0.48,0.48];
rgbExcluded = [0.25,0.25,0.25];
rgbBlack = [30,30,30]/255;

grayPointSize = 38;
representativePointSize = 70;

grayLineWidth = 1.4;
representativeLineWidth = 3.2;

showExcludedPoints = false;
showLegend = true;

% Optional manual limits. Use [] for automatic limits.

KLstdXLim = [];
KLstdYLim = [];

KLstrainXLim = [];
KLstrainYLim = [];

MIXLim = [];
MIYLim = [];

saveFigures = true;
saveCSV = true;
saveMAT = true;

%% ========================================================================
% 3. LOAD BUNDLING-PARAMETER DATA
%% ========================================================================

if ~isfile(BP_FILE)
    error('BP file was not found:\n%s',BP_FILE);
end

BPData = load(BP_FILE);

if isfield(BPData,'BP_Matrix')

    bundleParameter = double(BPData.BP_Matrix);

elseif isfield(BPData,'BP_FirstAverage')

    bundleParameter = double(BPData.BP_FirstAverage);

elseif isfield(BPData,'BP_SelectedFrames')

    bundleParameter = double(BPData.BP_SelectedFrames);

elseif isfield(BPData,'bundleParameter')

    bundleParameter = double(BPData.bundleParameter);

else

    error([ ...
        'No recognized BP matrix was found.\n', ...
        'Expected BP_Matrix, BP_FirstAverage, BP_SelectedFrames, ', ...
        'or bundleParameter.']);
end

if isfield(BPData,'experimentNumbers')

    BundlingExperiments = ...
        double(BPData.experimentNumbers(:));

elseif isfield(BPData,'Experiments_Two')

    BundlingExperiments = ...
        double(BPData.Experiments_Two(:));

else

    BundlingExperiments = [6 8 9 10 11 13]';

    warning( ...
        'Assuming BP experiment order [6 8 9 10 11 13].');
end

if size(bundleParameter,1) ~= numel(BundlingExperiments)

    error([ ...
        'The BP matrix has %d rows, but BundlingExperiments ', ...
        'contains %d experiment labels.'], ...
        size(bundleParameter,1), ...
        numel(BundlingExperiments));
end

fprintf('\n============================================\n');
fprintf('BUNDLING-PARAMETER DATA\n');
fprintf('============================================\n');

fprintf( ...
    'BP matrix size: %d x %d\n', ...
    size(bundleParameter,1), ...
    size(bundleParameter,2));

fprintf( ...
    'BP experiment order: %s\n', ...
    num2str(BundlingExperiments'));

%% ========================================================================
% 4. LOAD KL_STD AND KL_STRAIN
%% ========================================================================

if ~isfile(DATAOFKL_FILE)
    error('DATAOFKL.mat was not found:\n%s',DATAOFKL_FILE);
end

KLData = load(DATAOFKL_FILE);

if ~isfield(KLData,'KL_Frame')
    error('DATAOFKL.mat does not contain KL_Frame.');
end

if ~isfield(KLData,'strainKL')
    error('DATAOFKL.mat does not contain strainKL.');
end

KL_Frame = double(KLData.KL_Frame);
strainKL = double(KLData.strainKL);

if size(KL_Frame,1) ~= numel(BundlingExperiments)

    error([ ...
        'KL_Frame contains %d rows, but BP contains %d experiments.\n', ...
        'Confirm that the KL row order matches BundlingExperiments.'], ...
        size(KL_Frame,1), ...
        numel(BundlingExperiments));
end

if size(strainKL,1) ~= numel(BundlingExperiments)

    error([ ...
        'strainKL contains %d rows, but BP contains %d experiments.\n', ...
        'Confirm that the strain row order matches BundlingExperiments.'], ...
        size(strainKL,1), ...
        numel(BundlingExperiments));
end

numberCommonKLFrames = min([ ...
    NUM_FRAMES, ...
    size(bundleParameter,2), ...
    size(KL_Frame,2), ...
    size(strainKL,2)]);

if numberCommonKLFrames < 1
    error('No common BP/KL frames were found.');
end

KL_frame_indices = 1:numberCommonKLFrames;

BP_for_KL = ...
    bundleParameter(:,KL_frame_indices);

KLstd_all = ...
    KL_Frame(:,KL_frame_indices);

KLstrain_all = ...
    strainKL(:,KL_frame_indices);

%% ========================================================================
% 5. LOAD AND ALIGN SPATIAL MI
%% ========================================================================

if ~isfile(CUMULATIVE_MI_FILE)

    error( ...
        'Spatial-MI file was not found:\n%s', ...
        CUMULATIVE_MI_FILE);
end

MIData = load(CUMULATIVE_MI_FILE);

if ~isfield(MIData,'Experiments_Two')

    error( ...
        'The spatial-MI file does not contain Experiments_Two.');
end

MI_Experiments = ...
    double(MIData.Experiments_Two(:));

MI_Matrix_nats = ...
    selectMIMatrix(MIData,MIValueMode);

if size(MI_Matrix_nats,1) ~= numel(MI_Experiments)

    error([ ...
        'The selected MI matrix has %d rows, but Experiments_Two ', ...
        'contains %d labels.'], ...
        size(MI_Matrix_nats,1), ...
        numel(MI_Experiments));
end

MI_aligned_all = nan( ...
    numel(BundlingExperiments), ...
    size(MI_Matrix_nats,2));

for bpRow = 1:numel(BundlingExperiments)

    experimentNumber = ...
        BundlingExperiments(bpRow);

    miRow = find( ...
        MI_Experiments == experimentNumber, ...
        1, ...
        'first');

    if isempty(miRow)

        warning( ...
            'Experiment %d was not found in the MI file.', ...
            experimentNumber);

        continue;
    end

    MI_aligned_all(bpRow,:) = ...
        MI_Matrix_nats(miRow,:);
end

firstMIColumn = 1+MIFrameOffset;

if firstMIColumn < 1
    error('MIFrameOffset gives an invalid first MI column.');
end

numberCommonMIFrames = min([ ...
    NUM_FRAMES, ...
    size(bundleParameter,2), ...
    size(MI_aligned_all,2)-MIFrameOffset]);

if numberCommonMIFrames < 1

    error([ ...
        'No common BP/MI frames remain after applying ', ...
        'MIFrameOffset = %d.'], ...
        MIFrameOffset);
end

BP_MI_frame_indices = 1:numberCommonMIFrames;

MI_frame_indices = ...
    BP_MI_frame_indices+MIFrameOffset;

BP_for_MI = ...
    bundleParameter(:,BP_MI_frame_indices);

MI_all = ...
    MI_aligned_all(:,MI_frame_indices);

fprintf('\n============================================\n');
fprintf('SPATIAL MI DATA\n');
fprintf('============================================\n');

fprintf('MI mode: %s\n',MIValueMode);

fprintf( ...
    'BP columns %d:%d paired with MI columns %d:%d\n', ...
    BP_MI_frame_indices(1), ...
    BP_MI_frame_indices(end), ...
    MI_frame_indices(1), ...
    MI_frame_indices(end));

%% ========================================================================
% 6. APPLY EXPERIMENT REMOVAL SEPARATELY
%% ========================================================================

[ ...
    KLstdExperiments, ...
    BP_KLstd, ...
    KLstd_original] = ...
    selectExperiments( ...
        BundlingExperiments, ...
        BP_for_KL, ...
        KLstd_all, ...
        experimentsToRemove_KLstd, ...
        representativeExperiment_KLstd, ...
        'KL_std');

[ ...
    KLstrainExperiments, ...
    BP_KLstrain, ...
    KLstrain_original] = ...
    selectExperiments( ...
        BundlingExperiments, ...
        BP_for_KL, ...
        KLstrain_all, ...
        experimentsToRemove_KLstrain, ...
        representativeExperiment_KLstrain, ...
        'KL_strain');

[ ...
    MIExperiments, ...
    BP_MI, ...
    MI_original] = ...
    selectExperiments( ...
        BundlingExperiments, ...
        BP_for_MI, ...
        MI_all, ...
        experimentsToRemove_MI, ...
        representativeExperiment_MI, ...
        'Spatial MI');

fprintf('\n============================================\n');
fprintf('EXPERIMENT SELECTION\n');
fprintf('============================================\n');

fprintf( ...
    'KL_std removed: %s\n', ...
    numberListString(experimentsToRemove_KLstd));

fprintf( ...
    'KL_std representative: %d\n', ...
    representativeExperiment_KLstd);

fprintf( ...
    'KL_strain removed: %s\n', ...
    numberListString(experimentsToRemove_KLstrain));

fprintf( ...
    'KL_strain representative: %d\n', ...
    representativeExperiment_KLstrain);

fprintf( ...
    'MI removed: %s\n', ...
    numberListString(experimentsToRemove_MI));

fprintf( ...
    'MI representative: %d\n', ...
    representativeExperiment_MI);

%% ========================================================================
% 7. AUTOMATIC TEMPORAL FILTERING
%% ========================================================================

if applyAutomaticFiltering

    [ ...
        KLstd_filtered, ...
        KLstd_excludedMask, ...
        KLstd_OutlierTable, ...
        KLstd_DiagnosticTable] = ...
        detectMovingMedianOutliers( ...
            KLstd_original, ...
            KLstdExperiments, ...
            autoFilter, ...
            'KL_std');

    [ ...
        KLstrain_filtered, ...
        KLstrain_excludedMask, ...
        KLstrain_OutlierTable, ...
        KLstrain_DiagnosticTable] = ...
        detectMovingMedianOutliers( ...
            KLstrain_original, ...
            KLstrainExperiments, ...
            autoFilter, ...
            'KL_strain');

    [ ...
        MI_filtered, ...
        MI_excludedMask, ...
        MI_OutlierTable, ...
        MI_DiagnosticTable] = ...
        detectMovingMedianOutliers( ...
            MI_original, ...
            MIExperiments, ...
            autoFilter, ...
            'Spatial MI');

else

    KLstd_filtered = KLstd_original;
    KLstrain_filtered = KLstrain_original;
    MI_filtered = MI_original;

    KLstd_excludedMask = ...
        false(size(KLstd_original));

    KLstrain_excludedMask = ...
        false(size(KLstrain_original));

    MI_excludedMask = ...
        false(size(MI_original));

    KLstd_OutlierTable = table();
    KLstrain_OutlierTable = table();
    MI_OutlierTable = table();

    KLstd_DiagnosticTable = table();
    KLstrain_DiagnosticTable = table();
    MI_DiagnosticTable = table();
end

%% ========================================================================
% 8. FIT EACH EXPERIMENT SEPARATELY
%% ========================================================================

[ ...
    KLstd_FitTable, ...
    KLstd_LineData, ...
    KLstd_PointTable] = ...
    fitIndividualExperiments( ...
        BP_KLstd, ...
        KLstd_filtered, ...
        KLstd_original, ...
        KLstd_excludedMask, ...
        KLstdExperiments);

[ ...
    KLstrain_FitTable, ...
    KLstrain_LineData, ...
    KLstrain_PointTable] = ...
    fitIndividualExperiments( ...
        BP_KLstrain, ...
        KLstrain_filtered, ...
        KLstrain_original, ...
        KLstrain_excludedMask, ...
        KLstrainExperiments);

[ ...
    MI_FitTable, ...
    MI_LineData, ...
    MI_PointTable] = ...
    fitIndividualExperiments( ...
        BP_MI, ...
        MI_filtered, ...
        MI_original, ...
        MI_excludedMask, ...
        MIExperiments);

fprintf('\n============================================\n');
fprintf('KL_STD FITS\n');
fprintf('============================================\n');
disp(KLstd_FitTable);

fprintf('\n============================================\n');
fprintf('KL_STRAIN FITS\n');
fprintf('============================================\n');
disp(KLstrain_FitTable);

fprintf('\n============================================\n');
fprintf('SPATIAL MI FITS\n');
fprintf('============================================\n');
disp(MI_FitTable);

