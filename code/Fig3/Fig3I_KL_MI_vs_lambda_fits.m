end

function [resultsTable,lineData,pointTable] = ...
        fitIndividualExperiments( ...
            XMatrix, ...
            YFilteredMatrix, ...
            YOriginalMatrix, ...
            excludedMask, ...
            experimentNumbers)

    if ~isequal(size(XMatrix),size(YFilteredMatrix)) || ...
            ~isequal(size(XMatrix),size(YOriginalMatrix)) || ...
            ~isequal(size(XMatrix),size(excludedMask))

        error([ ...
            'X, filtered Y, original Y, and exclusion mask ', ...
            'must have identical dimensions.']);
    end

    numberExperiments = size(XMatrix,1);

    experimentNumbers = experimentNumbers(:);

    Experiment = experimentNumbers;

    N = zeros(numberExperiments,1);
    NExcluded = zeros(numberExperiments,1);

    Slope = nan(numberExperiments,1);
    SlopeSE = nan(numberExperiments,1);
    SlopeCI_Lower = nan(numberExperiments,1);
    SlopeCI_Upper = nan(numberExperiments,1);

    Intercept = nan(numberExperiments,1);

    R2 = nan(numberExperiments,1);
    AdjustedR2 = nan(numberExperiments,1);
    PValue = nan(numberExperiments,1);

    lineData = cell(numberExperiments,1);

    PointExperiment = [];
    PointFrame = [];
    PointBP = [];
    PointResponse = [];

    PointIncluded = false(0,1);
    PointAutoExcluded = false(0,1);

    for experimentIndex = 1:numberExperiments

        currentX = ...
            XMatrix(experimentIndex,:);

        currentYFiltered = ...
            YFilteredMatrix(experimentIndex,:);

        currentYOriginal = ...
            YOriginalMatrix(experimentIndex,:);

        currentExcluded = ...
            excludedMask(experimentIndex,:);

        fitMask = ...
            isfinite(currentX) & ...
            isfinite(currentYFiltered);

        originalMask = ...
            isfinite(currentX) & ...
            isfinite(currentYOriginal);

        xFit = currentX(fitMask)';
        yFit = currentYFiltered(fitMask)';

        N(experimentIndex) = ...
            numel(xFit);

        NExcluded(experimentIndex) = ...
            nnz(originalMask & currentExcluded);

        if numel(xFit) >= 3 && ...
                numel(unique(xFit)) >= 2

            mdl = fitlm(xFit,yFit);

            Intercept(experimentIndex) = ...
                mdl.Coefficients.Estimate(1);

            Slope(experimentIndex) = ...
                mdl.Coefficients.Estimate(2);

            SlopeSE(experimentIndex) = ...
                mdl.Coefficients.SE(2);

            R2(experimentIndex) = ...
                mdl.Rsquared.Ordinary;

            AdjustedR2(experimentIndex) = ...
                mdl.Rsquared.Adjusted;

            PValue(experimentIndex) = ...
                mdl.Coefficients.pValue(2);

            coefficientCI = ...
                coefCI(mdl,0.05);

            SlopeCI_Lower(experimentIndex) = ...
                coefficientCI(2,1);

            SlopeCI_Upper(experimentIndex) = ...
                coefficientCI(2,2);

            xLine = linspace( ...
                min(xFit), ...
                max(xFit), ...
                200)';

            yLine = predict(mdl,xLine);

            lineData{experimentIndex} = ...
                [xLine,yLine];
        end

        for frameIndex = 1:size(XMatrix,2)

            if ~originalMask(frameIndex)
                continue;
            end

            PointExperiment(end+1,1) = ...
                experimentNumbers(experimentIndex); %#ok<AGROW>

            PointFrame(end+1,1) = ...
                frameIndex; %#ok<AGROW>

            PointBP(end+1,1) = ...
                currentX(frameIndex); %#ok<AGROW>

            PointResponse(end+1,1) = ...
                currentYOriginal(frameIndex); %#ok<AGROW>

            PointIncluded(end+1,1) = ...
                fitMask(frameIndex); %#ok<AGROW>

            PointAutoExcluded(end+1,1) = ...
                currentExcluded(frameIndex); %#ok<AGROW>
        end
    end

    resultsTable = table( ...
        Experiment, ...
        N, ...
        NExcluded, ...
        Slope, ...
        SlopeSE, ...
        SlopeCI_Lower, ...
        SlopeCI_Upper, ...
        Intercept, ...
        R2, ...
        AdjustedR2, ...
        PValue);

    pointTable = table( ...
        PointExperiment, ...
        PointFrame, ...
        PointBP, ...
        PointResponse, ...
        PointIncluded, ...
        PointAutoExcluded, ...
        'VariableNames',{ ...
            'Experiment', ...
            'AnalysisFrame', ...
            'BundlingParameter', ...
            'Response', ...
            'IncludedInFit', ...
            'AutomaticallyExcluded'});
end

