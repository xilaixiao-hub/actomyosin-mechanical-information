title( ...
    axEarly, ...
    sprintf('Frame %d',frameEarly), ...
    'FontWeight','normal');

set( ...
    axEarly, ...
    'FontName','Arial', ...
    'FontSize',FZ, ...
    'LineWidth',1.7, ...
    'TickDir','in', ...
    'Box','on');

%% ============================================================
% FIGURE 2: LATE FRAME
%% ============================================================

figLate = figure( ...
    'Name',sprintf('Frame %d',frameLate), ...
    'Color','w', ...
    'Position',[800,100,650,600]);

axLate = axes(figLate);

imagesc(axLate,imageLate);
axis(axLate,'image');
set(axLate,'YDir','normal');
colormap(axLate,purpleColormap(256));
clim(axLate,commonCLim);

hold(axLate,'on');

if showActivationCircles

    drawActivationCircles( ...
        axLate, ...
        activationCenters_px, ...
        activationRadii_px, ...
        rgbCircle, ...
        2.5);

end

rectangle( ...
    axLate, ...
    'Position',roiPosition, ...
    'EdgeColor',rgbRectangle, ...
    'LineWidth',3);

hold(axLate,'off');

xlabel(axLate,'x (pixels)');
ylabel(axLate,'y (pixels)');

title( ...
    axLate, ...
    sprintf('Frame %d',frameLate), ...
    'FontWeight','normal');

set( ...
    axLate, ...
    'FontName','Arial', ...
    'FontSize',FZ, ...
    'LineWidth',1.7, ...
    'TickDir','in', ...
    'Box','on');

%% ============================================================
% FIGURE 3: SQUARE AVERAGED LINE-SCAN PLOT
%% ============================================================

% Mean profile across all horizontal lines.
averageProfileEarly = mean( ...
    roiEarly, ...
    1, ...
    'omitnan');

averageProfileLate = mean( ...
    roiLate, ...
    1, ...
    'omitnan');

% SD across horizontal lines at each x position.
stdProfileEarly = std( ...
    roiEarly, ...
    0, ...
    1, ...
    'omitnan');

stdProfileLate = std( ...
    roiLate, ...
    0, ...
    1, ...
    'omitnan');

% BP calculated from the overall averaged profile.
bpEarly = std( ...
    averageProfileEarly, ...
