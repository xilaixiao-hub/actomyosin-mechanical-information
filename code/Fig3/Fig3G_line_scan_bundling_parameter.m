function displayPurpleImage(axisHandle,imageMatrix,displayPercentiles)

    imagesc(axisHandle,imageMatrix);

    axis(axisHandle,'image');
    set(axisHandle,'YDir','normal');

    colormap(axisHandle,purpleColormap(256));

    finitePixels = imageMatrix(isfinite(imageMatrix));

    if ~isempty(finitePixels)

        limits = prctile(finitePixels,displayPercentiles);

        if limits(2) > limits(1)
            clim(axisHandle,limits);
        end

    end

end


function cmap = purpleColormap(numberColors)

    anchorColors = [ ...
        1.00,1.00,1.00; ...
        0.91,0.84,0.94; ...
        0.66,0.43,0.75; ...
        0.38,0.14,0.49; ...
        0.12,0.03,0.17];

    anchorPositions = linspace(0,1,size(anchorColors,1));
    queryPositions = linspace(0,1,numberColors);

    cmap = interp1( ...
        anchorPositions, ...
        anchorColors, ...
        queryPositions, ...
        'pchip');

    cmap = min(max(cmap,0),1);

end


function drawActivationCircles( ...
        axisHandle, ...
        centers_px, ...
        radii_px, ...
        circleColor, ...
        lineWidth)

    theta = linspace(0,2*pi,500);

    for circleIndex = 1:numel(radii_px)

        xCircle = ...
            centers_px(circleIndex,1) + ...
            radii_px(circleIndex)*cos(theta);

        yCircle = ...
            centers_px(circleIndex,2) + ...
            radii_px(circleIndex)*sin(theta);

        plot( ...
            axisHandle, ...
            xCircle, ...
            yCircle, ...
            '-', ...
            'Color',circleColor, ...
            'LineWidth',lineWidth);

    end

end


function [xStart,yStart,xEnd,yEnd] = ...
        rectangleToPixelBounds( ...
            rectanglePosition, ...
            numberColumns, ...
            numberRows)

    xStart = max(1,round(rectanglePosition(1)));
    yStart = max(1,round(rectanglePosition(2)));

    xEnd = min( ...
        numberColumns, ...
        round(rectanglePosition(1)+rectanglePosition(3)));

    yEnd = min( ...
        numberRows, ...
        round(rectanglePosition(2)+rectanglePosition(4)));

    if xEnd <= xStart || yEnd <= yStart
        error('The selected rectangle is too small.');
    end

end


function formatAxes(axisHandle,fontSize)

    set( ...
        axisHandle, ...
        'FontName','Arial', ...
        'FontSize',fontSize-3, ...
        'LineWidth',1.7, ...
        'TickDir','in', ...
        'Box','on');

end
