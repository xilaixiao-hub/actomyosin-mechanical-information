function [filteredMatrix,outlierMask,outlierTable,diagnosticTable] = ...
        detectMovingMedianOutliers( ...
            inputMatrix, ...
            experimentNumbers, ...
            settings, ...
            dataName)

    filteredMatrix = inputMatrix;
    outlierMask = false(size(inputMatrix));

    numberExperiments = size(inputMatrix,1);
    numberFrames = size(inputMatrix,2);

    halfWindow = ...
        floor(settings.windowSize/2);

    DiagnosticExperiment = [];
    DiagnosticFrame = [];
    DiagnosticValue = [];
    DiagnosticLocalMedian = [];
    DiagnosticLocalMAD = [];
    DiagnosticRobustScale = [];
    DiagnosticRobustScore = [];

    DiagnosticFlagged = false(0,1);

    for experimentIndex = 1:numberExperiments

        y = ...
            inputMatrix(experimentIndex,:);

        localMedian = ...
            nan(1,numberFrames);

        localMAD = ...
            nan(1,numberFrames);

        robustScale = ...
            nan(1,numberFrames);

        robustScore = ...
            nan(1,numberFrames);

        finiteValues = ...
            y(isfinite(y));

        if isempty(finiteValues)
            continue;
        end

        valueRange = ...
            max(finiteValues)-min(finiteValues);

        if numel(finiteValues) >= 2

            valueSD = ...
                std(finiteValues,0);

        else

            valueSD = 0;
        end

        scaleFloor = ...
            settings.minimumScaleFraction * ...
            max([valueRange,valueSD,eps]);

        for frameIndex = 1:numberFrames

            firstFrame = ...
                max(1,frameIndex-halfWindow);

            lastFrame = ...
                min(numberFrames,frameIndex+halfWindow);

            localValues = ...
                y(firstFrame:lastFrame);

            localValues = ...
                localValues(isfinite(localValues));

            if ~isfinite(y(frameIndex)) || ...
                    numel(localValues) < ...
                    settings.minimumWindowPoints

                continue;
            end

            localMedian(frameIndex) = ...
                median(localValues);

            localMAD(frameIndex) = ...
                median( ...
                    abs( ...
                        localValues- ...
                        localMedian(frameIndex)));

            robustScale(frameIndex) = ...
                max( ...
                    1.4826*localMAD(frameIndex), ...
                    scaleFloor);

            robustScore(frameIndex) = ...
                abs( ...
                    y(frameIndex)- ...
                    localMedian(frameIndex)) / ...
                robustScale(frameIndex);
        end

        candidateMask = ...
            isfinite(robustScore) & ...
            robustScore > settings.thresholdFactor;

        if settings.protectEndpoints

            candidateMask(1) = false;
            candidateMask(end) = false;
        end

        candidateMask = ...
            retainOnlyShortRuns( ...
                candidateMask, ...
                settings.maximumConsecutiveOutliers);

        excludedFraction = ...
            nnz(candidateMask) / ...
            max(nnz(isfinite(y)),1);

        if excludedFraction > ...
                settings.maximumExcludedFraction

            warning([ ...
                '%s, Experiment %g: %.1f%% of finite points were ', ...
                'flagged, exceeding the %.1f%% safety limit. ', ...
                'No points were excluded.'], ...
                dataName, ...
                experimentNumbers(experimentIndex), ...
                100*excludedFraction, ...
                100*settings.maximumExcludedFraction);

            candidateMask(:) = false;
        end

        outlierMask(experimentIndex,:) = ...
            candidateMask;

        for frameIndex = 1:numberFrames

            DiagnosticExperiment(end+1,1) = ...
                experimentNumbers(experimentIndex); %#ok<AGROW>

            DiagnosticFrame(end+1,1) = ...
                frameIndex; %#ok<AGROW>

            DiagnosticValue(end+1,1) = ...
                y(frameIndex); %#ok<AGROW>

            DiagnosticLocalMedian(end+1,1) = ...
                localMedian(frameIndex); %#ok<AGROW>

            DiagnosticLocalMAD(end+1,1) = ...
                localMAD(frameIndex); %#ok<AGROW>

            DiagnosticRobustScale(end+1,1) = ...
                robustScale(frameIndex); %#ok<AGROW>

            DiagnosticRobustScore(end+1,1) = ...
                robustScore(frameIndex); %#ok<AGROW>

            DiagnosticFlagged(end+1,1) = ...
                logical(candidateMask(frameIndex)); %#ok<AGROW>
        end
    end

    filteredMatrix(outlierMask) = NaN;

    diagnosticTable = table( ...
        DiagnosticExperiment, ...
        DiagnosticFrame, ...
        DiagnosticValue, ...
        DiagnosticLocalMedian, ...
        DiagnosticLocalMAD, ...
        DiagnosticRobustScale, ...
        DiagnosticRobustScore, ...
        logical(DiagnosticFlagged), ...
        'VariableNames',{ ...
            'Experiment', ...
            'Frame', ...
            'Value', ...
            'LocalMedian', ...
            'LocalMAD', ...
            'RobustScale', ...
            'RobustScore', ...
            'Flagged'});

    outlierTable = ...
        diagnosticTable( ...
            logical(diagnosticTable.Flagged),:);

    fprintf( ...
        '%s: automatically excluded %d of %d finite points.\n', ...
        dataName, ...
        nnz(outlierMask), ...
        nnz(isfinite(inputMatrix)));
end

function cleanedMask = ...
        retainOnlyShortRuns( ...
            candidateMask, ...
            maximumRunLength)

    cleanedMask = ...
        logical(candidateMask);

    paddedMask = ...
        [false,cleanedMask,false];

    transitions = ...
        diff(paddedMask);

    runStarts = ...
        find(transitions == 1);

    runEnds = ...
        find(transitions == -1)-1;

    for runIndex = 1:numel(runStarts)

        runLength = ...
            runEnds(runIndex)- ...
            runStarts(runIndex)+1;

        if runLength > maximumRunLength

            cleanedMask( ...
                runStarts(runIndex): ...
                runEnds(runIndex)) = false;
        end
    end
end

function numericMatrix = ...
        cellScalarMatrixToNumeric(cellMatrix)

    numericMatrix = ...
        nan(size(cellMatrix));

    for rowIndex = 1:size(cellMatrix,1)

        for columnIndex = 1:size(cellMatrix,2)

            currentValue = ...
                cellMatrix{rowIndex,columnIndex};

            if isnumeric(currentValue) && ...
                    isscalar(currentValue) && ...
                    isfinite(currentValue)

                numericMatrix(rowIndex,columnIndex) = ...
                    double(currentValue);
            end
        end
    end
end

function setAxisLimitsFromData( ...
        axisHandle,xData,yData)

    valid = ...
        isfinite(xData) & ...
        isfinite(yData);

    if ~any(valid)
        return;
    end

    xData = xData(valid);
    yData = yData(valid);

    xMinimum = min(xData);
    xMaximum = max(xData);

    yMinimum = min(yData);
    yMaximum = max(yData);

    xRange = xMaximum-xMinimum;
    yRange = yMaximum-yMinimum;

    if xRange <= 0
        xRange = max(abs([xMinimum,xMaximum]));
    end

    if yRange <= 0
        yRange = max(abs([yMinimum,yMaximum]));
    end

    if xRange <= 0
        xRange = 1;
    end

    if yRange <= 0
        yRange = 1;
    end

    xPadding = 0.08*xRange;
    yPadding = 0.08*yRange;

    xlim( ...
        axisHandle, ...
        [ ...
            xMinimum-xPadding, ...
            xMaximum+xPadding ...
        ]);

    ylim( ...
        axisHandle, ...
        [ ...
            yMinimum-yPadding, ...
            yMaximum+yPadding ...
        ]);
end

function formatPaperAxes( ...
        axisHandle,fontSize,blackColor)

    set( ...
        axisHandle, ...
        'FontName','Arial', ...
        'FontSize',fontSize, ...
        'LineWidth',1.5, ...
        'TickDir','in', ...
        'TickLength',[0.018,0.018], ...
        'Box','on', ...
        'XColor',blackColor, ...
        'YColor',blackColor, ...
        'Layer','top');

    grid(axisHandle,'off');
end

function saveVectorAndPNG( ...
        figureHandle, ...
        outputDirectory, ...
        baseName)

    if isempty(figureHandle) || ...
            ~isgraphics(figureHandle)

        return;
    end

    set( ...
        figureHandle, ...
        'Renderer','painters');

    exportgraphics( ...
        figureHandle, ...
        fullfile( ...
            outputDirectory, ...
            [baseName '.pdf']), ...
        'ContentType','vector');

    exportgraphics( ...
        figureHandle, ...
        fullfile( ...
            outputDirectory, ...
            [baseName '.eps']), ...
        'ContentType','vector');

    exportgraphics( ...
        figureHandle, ...
        fullfile( ...
            outputDirectory, ...
            [baseName '.png']), ...
        'Resolution',600);
end

