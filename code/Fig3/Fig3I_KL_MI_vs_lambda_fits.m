function MI_nats = selectMIMatrix(MIData,MIValueMode)

    switch lower(MIValueMode)

        case 'raw'

            if isfield(MIData,'MI_Raw_nats')

                MI_nats = ...
                    double(MIData.MI_Raw_nats);

            elseif isfield(MIData,'MI_Raw_bits')

                MI_nats = ...
                    double(MIData.MI_Raw_bits)*log(2);

            else

                error([ ...
                    'MIValueMode is raw, but the file contains neither ', ...
                    'MI_Raw_nats nor MI_Raw_bits.']);
            end

        case 'corrected'

            if isfield(MIData,'MI_BiasCorrected_nats')

                MI_nats = ...
                    double(MIData.MI_BiasCorrected_nats);

            elseif isfield(MIData,'MI_BiasCorrected_bits')

                MI_nats = ...
                    double(MIData.MI_BiasCorrected_bits)*log(2);

            elseif isfield(MIData,'spatialMI')

                MI_nats = ...
                    cellScalarMatrixToNumeric(MIData.spatialMI);

            else

                error([ ...
                    'MIValueMode is corrected, but no corrected-MI ', ...
                    'variable was found.']);
            end

        case 'excess'

            if isfield(MIData,'MI_Excess_nats')

                MI_nats = ...
                    double(MIData.MI_Excess_nats);

            elseif isfield(MIData,'MI_Excess_bits')

                MI_nats = ...
                    double(MIData.MI_Excess_bits)*log(2);

            else

                error([ ...
                    'MIValueMode is excess, but the file contains neither ', ...
                    'MI_Excess_nats nor MI_Excess_bits.']);
            end

        otherwise

            error( ...
                'Unknown MIValueMode: %s', ...
                MIValueMode);
    end
end

function [retainedExperiments,XRetained,YRetained] = ...
        selectExperiments( ...
            allExperiments, ...
            XMatrix, ...
            YMatrix, ...
            experimentsToRemove, ...
            representativeExperiment, ...
            analysisName)

    allExperiments = allExperiments(:);

    experimentsToRemove = ...
        unique(double(experimentsToRemove(:)));

    unknownExperiments = ...
        setdiff(experimentsToRemove,allExperiments);

    if ~isempty(unknownExperiments)

        warning( ...
            '%s removal list contains unknown experiments: %s', ...
            analysisName, ...
            num2str(unknownExperiments'));
    end

    retainedMask = ...
        ~ismember(allExperiments,experimentsToRemove);

    retainedExperiments = ...
        allExperiments(retainedMask);

